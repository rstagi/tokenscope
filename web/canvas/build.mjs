// Builds the session canvas into the Python package: tokenscope/live/static/canvas.js + canvas.css (the bundled
// libraries' licence comments go to canvas.js.LEGAL.txt), and regenerates THIRD_PARTY_NOTICES.md at the repo root
// from the packages that actually end up in the bundle. Run: npm ci && npm run build (see README.md).
import {build} from "esbuild";
import {fileURLToPath} from "node:url";
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, "..", "..");
const res = await build({
  entryPoints: [path.join(here, "src", "main.jsx")],
  outfile: path.join(repo, "tokenscope", "live", "static", "canvas.js"),
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2019"],
  jsx: "automatic",
  legalComments: "external",
  metafile: true,
  define: {"process.env.NODE_ENV": '"production"'},
  logLevel: "info",
});

const pkgs = new Set();
for (const f of Object.keys(res.metafile.inputs)) {
  const m = f.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (m) pkgs.add(m[1]);
}
const out = ["# Third-party notices", "",
  "tokenscope is MIT-licensed (see LICENSE). The web session canvas (`tokenscope/live/static/canvas.js` and",
  "`canvas.css`, built from `web/canvas/` by `web/canvas/build.mjs`) bundles the packages below. All are under",
  "permissive licences (MIT, ISC, BSD-3-Clause) compatible with MIT; each requires its copyright notice and licence",
  "text to accompany copies, reproduced here. This file is generated by the build.", "",
  "No EPL-2.0 code is bundled: elkjs (EPL-2.0) was considered for layout and not used; EPL-2.0 is a weak copyleft",
  "licence whose file-level source-availability terms would apply to a bundled copy, so the canvas uses its own small",
  "incremental layout instead (dagre, MIT, would also have been fine).", "",
  "| package | version | licence |", "|---|---|---|"];
const texts = [];
for (const p of [...pkgs].sort()) {
  const dir = path.join(here, "node_modules", p);
  const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  out.push(`| ${p} | ${pj.version} | ${pj.license} |`);
  const lic = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  texts.push(`## ${p} ${pj.version} (${pj.license})`, "", "```",
    lic ? fs.readFileSync(path.join(dir, lic), "utf8").trim() : `${pj.license} licence; no licence file in the package.`, "```", "");
}
fs.writeFileSync(path.join(repo, "THIRD_PARTY_NOTICES.md"), out.concat([""], texts).join("\n"));
console.log("THIRD_PARTY_NOTICES.md: %d packages", pkgs.size);
